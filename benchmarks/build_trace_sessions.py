#!/usr/bin/env python
"""Build the G2 agent-trace JSONL from the public parquet corpus.

The G2 runners take `--jsonl`, a one-object-per-line file whose rows carry the
conversation in any of the forms `messages_from_row` accepts (`messages_json`,
`messages`, `trajectory`) plus, optionally, `source_dataset` and `max_isl`.  The public
corpus ships as a single parquet, so this script is the only step between "download the
dataset" and "run the gate" - and it exists because the first G2 receipt was produced
from a `/tmp` file that was later lost, which made the run unreproducible.

The JSONL is deliberately *not* committed: 15,000 sessions of real agent transcripts are
hundreds of megabytes.  What is committed is this script plus the artifact it produces,
so the receipt can be regenerated byte-for-byte from a public dataset.

Requires an interpreter with `pyarrow` (or `pandas`) and `huggingface_hub`; it is a data
step and does not touch the GPU or the project's own dependencies.

Usage:
    python benchmarks/build_trace_sessions.py --out data/sessions.jsonl
    python benchmarks/build_trace_sessions.py --out data/sessions.jsonl \
        --source thoughtworks/agentic-coding-trajectories --max-sessions 15000

Before downloading, note that the HTTP client stack needs a `no_proxy` value httpx can
parse (a bracketed IPv6 entry such as `[::1]` raises `InvalidURL: Invalid port`), e.g.
`no_proxy=localhost,127.0.0.1,::1`.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

# fields the G2 runners read; everything else in the parquet is metadata the gate does
# not use, and dropping it keeps the JSONL small enough to stream comfortably
_KEEP = ("messages_json", "messages", "trajectory", "source_dataset", "source_id",
         "session_id", "agent_framework", "recorded_model", "max_isl", "n_turns",
         "total_tokens")


def read_rows(path: Path) -> list[dict]:
    try:
        import pyarrow.parquet as pq
    except ImportError:                                     # pragma: no cover
        import pandas                                        # type: ignore

        return pandas.read_parquet(path).to_dict(orient="records")
    return pq.ParquetFile(path).read().to_pylist()


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", default="thoughtworks/agentic-coding-trajectories")
    parser.add_argument("--filename", default="sessions.parquet")
    parser.add_argument("--parquet", default=None,
                        help="use an already-downloaded parquet instead of fetching")
    parser.add_argument("--out", required=True)
    parser.add_argument("--max-sessions", type=int, default=0)
    parser.add_argument("--require-messages", action="store_true", default=True)
    args = parser.parse_args(argv)

    if args.parquet:
        parquet = Path(args.parquet)
    else:
        from huggingface_hub import hf_hub_download
        parquet = Path(hf_hub_download(args.source, args.filename, repo_type="dataset"))

    rows = read_rows(parquet)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    written = skipped = 0
    with out.open("w") as handle:
        for row in rows:
            record = {k: row[k] for k in _KEEP if k in row and row[k] is not None}
            has_messages = any(k in record for k in ("messages_json", "messages",
                                                     "trajectory"))
            if args.require_messages and not has_messages:
                skipped += 1
                continue
            handle.write(json.dumps(record) + "\n")
            written += 1
            if args.max_sessions and written >= args.max_sessions:
                break
    print(f"wrote {written} sessions to {out} "
          f"(skipped {skipped} without a message field, {len(rows)} in {parquet.name})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
